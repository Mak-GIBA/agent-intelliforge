"""Research locations. Existing topics retain their original layout."""
from __future__ import annotations
import json
import os
from pathlib import Path
import re

PUBLIC = Path('docs/design-research')
LOCAL = Path('.artifacts/design-research')
MARKER = 'design-research-split-v1'
SLUG = re.compile(r'[a-z0-9][a-z0-9-]{0,63}\Z')


def checked(path):
    path = Path(os.path.abspath(path))
    if any(p.is_symlink() for p in (path, *path.parents)):
        raise ValueError('Research paths must not contain symlinks')
    return path


def topic_workspace(project, topic, create=False):
    if not SLUG.fullmatch(topic):
        raise ValueError('Unsafe research topic')
    project = checked(project)
    public, local = checked(project/PUBLIC/topic), checked(project/LOCAL/topic)
    if local.exists():
        if not split(local):
            raise ValueError('Unmanaged local research directory')
        return local
    if public.exists():
        return public  # Never migrate existing topics as a side effect.
    if create:
        local.mkdir(parents=True)
        (local/'workspace-layout.json').write_text(json.dumps({'generator':MARKER}), encoding='utf-8')
        ignore = checked(project/'.gitignore')
        old = ignore.read_text('utf-8') if ignore.exists() else ''
        rule = '/.artifacts/design-research/'
        if rule not in old.splitlines():
            ignore.write_text(old + ('' if not old or old.endswith('\n') else '\n') + rule+'\n', encoding='utf-8')
    return local


def split(workspace):
    marker = checked(Path(workspace)/'workspace-layout.json')
    if not marker.is_file():
        return False
    return json.loads(marker.read_text('utf-8')) == {'generator':MARKER}


def public_topic(workspace):
    workspace = checked(workspace)
    return workspace.parents[2]/PUBLIC/workspace.name if split(workspace) else workspace


def state_paths(project, run_id='*'):
    if run_id != '*' and not re.fullmatch(r'[A-Za-z0-9_-]{1,80}',run_id):
        raise ValueError('Unsafe run ID')
    return sorted(p for base in (PUBLIC,LOCAL) for p in checked(Path(project)/base).glob('*/runs/'+run_id+'/state.json'))


def state_identity(project, path):
    rel = checked(path).relative_to(checked(project)).parts
    if (len(rel)!=6 or Path(*rel[:2]) not in (PUBLIC,LOCAL)
            or rel[3]!='runs' or rel[5]!='state.json'):
        raise ValueError('Use an exact local or legacy topic/runs/<run-id>/state.json')
    if Path(*rel[:2])==LOCAL and not split(Path(path).parents[2]):
        raise ValueError('Unmanaged research workspace')
    return rel[2],rel[4]


def publish_public(state, workspace):
    """Publish human prose and figures; archived reports and receipts remain local."""
    if not split(workspace):
        return
    from runtime import atomic_bytes
    public = checked(public_topic(workspace));public.mkdir(parents=True,exist_ok=True)
    target = checked(public/'report.md')
    ownership = '<!-- Generated by design-research public-v1 -->'
    if target.exists() and not target.read_text('utf-8').startswith(ownership):
        raise ValueError('Refusing to overwrite an unmanaged public report')
    source = workspace/'report.md'
    if not source.is_file():
        return
    def rebase(match):
        name=match[1]
        if name.startswith(('http:','https:','#','mailto:')):
            return match[0]
        path=checked(workspace/name)
        if not path.is_relative_to(workspace):
            raise ValueError('Public report link escapes the research workspace')
        if path.suffix.lower() in {'.png','.jpg','.jpeg','.gif','.svg','.webp'} and path.is_file():
            dest=checked(public/'figures'/path.relative_to(workspace))
            atomic_bytes(dest,path.read_bytes())
            return ']('+dest.relative_to(public).as_posix()+')'
        return ']('+os.path.relpath(path,public)+')'
    text=re.sub(r'\]\(([^)]+)\)',rebase,source.read_text('utf-8'))
    atomic_bytes(target,(ownership+'\n\n'+text).encode('utf-8'))
    refresh_navigation(workspace.parents[2])


def refresh_navigation(project):
    """Use the installed Upstream CLI after mutations; never during inspection."""
    import shutil
    import subprocess
    cli=shutil.which('speckit-workbench')
    if cli and (Path(project)/'.specify/workbench.json').is_file():
        result=subprocess.run([cli,'overview','--project',str(project),'--write'],capture_output=True,text=True)
        if result.returncode:
            # Research evidence is already saved; navigation must not mask it.
            print('[DR-GAN] Navigation refresh: '+result.stderr.strip())


def generated_navigation(project,name):
    config=Path(project)/'.specify/workbench.json'
    if not config.is_file():return False
    docs=json.loads(config.read_text('utf-8')).get('docs_dir','docs/upstream')
    path=Path(project)/name
    return (name==docs.rstrip('/')+'/README.md' and path.is_file()
            and path.read_text('utf-8').startswith('<!-- Generated by speckit-workbench overview-v1 -->'))
