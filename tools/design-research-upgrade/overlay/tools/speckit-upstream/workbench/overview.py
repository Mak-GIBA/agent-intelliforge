def review_markdown(packet):
    lines=[f"# Upstream Review — {packet['review_id']}",'',f"確認段階: {packet['checkpoint']} / 対象: {packet['system']}",'',
           '以下の本文とIDを確認し、承認するIDまたは修正点を指定してください。','', '## 対象IDと判断する内容','']
    for item in packet['items']:
        lines += [f"- `{item['id']}` — {item['title']} / 状態: {item['status']} / 根拠: {item['basis']} / 承認: {item['approval_state']} / {item['file']}:{item['line']}"]
        for key in ('acceptance','expected','sources'):
            if item.get(key):lines.append(f"  - {key}: {item[key]}")
    lines+=['','## 本文と共通条件','']
    for name,doc in packet.get('documents',{}).items():lines += ['### '+name,'',doc['prose'],'']
    lines+=['## 未解決事項の確認','']
    pending=[item for item in packet['items'] if item['basis'] in {'unknown','proposed'} or item['approval_state']!='valid']
    lines += [f"- `{item['id']}`: 根拠は{item['basis']}、承認は{item['approval_state']}。本文の条件・未確認点を確認してください。" for item in pending]
    lines += ['','矛盾、適用範囲、未実行の検証は本文でも確認してください。レビューの作成自体は承認を記録しません。','',
            '承認する場合は対象IDを明示してください。「全部承認」はこのレビュー全体を確認した場合だけ指定します。','',
            '## 検証用の固定情報','', '````json',json.dumps(packet,ensure_ascii=False,indent=2),'````','']
    return '\n'.join(lines)
