MARKER='<!-- Generated by speckit-workbench overview-v1 -->'


def evidence_hashes(root,path,text):
    """New v3 bindings pin actual proof bytes in approvals; legacy hashes stay intact."""
    from .design_quality import bindings,sha
    from .published_evidence import safe
    try:data=bindings(text)
    except (ValueError,TypeError):return None
    if data['schema_version']!=3:return None
    paths=set()
    for row in data.get('runs',[]):
        if not isinstance(row,dict):continue
        name=row.get('evidence_manifest')
        if not isinstance(name,str):continue
        try:
            manifest=safe(root,name);paths.add(manifest)
            obj=json.loads(manifest.read_text('utf-8'))
            paths.update(safe(manifest.parent/'files',n) for n in obj['files'])
        except (OSError,ValueError,TypeError,KeyError):continue
    return {p.relative_to(root).as_posix():sha(p.read_bytes()) if p.is_file() else 'missing' for p in sorted(paths)}


def owned_navigation(root,path):
    config=load_project(root)
    target=inside(root,config['docs_dir']+'/README.md')
    return path==target and path.is_file() and path.read_text('utf-8').startswith(MARKER+'\n')


def research_status(root):
    from .workspace_paths import state_paths,state_identity
    from .published_evidence import verify
    rows=[];warnings=[];seen=set()
    for path in state_paths(root):
        try:
            state=json.loads(path.read_text('utf-8'))
            topic,run_id=state_identity(root,path)
            if state.get('schema_version')!=1 or state.get('run_id')!=run_id or state.get('config',{}).get('slug')!=topic:
                raise ValueError('Research state identity does not match its path')
            row={'run_id':state['run_id'],'topic':state['config']['slug'],'status':state['status'],
                 'phase':state.get('phase'),'state':path.relative_to(root).as_posix(),
                 'workstream_id':state.get('workstream_context',{}).get('workstream_id'),
                 'plan_sha256':state.get('workstream_context',{}).get('plan_sha256'),
                 'exported':False}
            rows.append(row);seen.add((row['topic'],row['run_id']))
        except (OSError,ValueError,TypeError,KeyError) as exc:warnings.append(str(exc))
    for path in sorted((root/'docs/design-research').glob('*/evidence/*/manifest.json')):
        try:
            manifest=verify(path.parent);identity=(manifest['topic'],manifest['run_id'])
            row=next((r for r in rows if (r['topic'],r['run_id'])==identity),None)
            if row is None:
                state=json.loads((path.parent/'files'/manifest['state']).read_text('utf-8'))
                row={'run_id':manifest['run_id'],'topic':manifest['topic'],'status':state['status'],
                     'phase':state.get('phase'),'local_workspace':False,
                     'workstream_id':state.get('workstream_context',{}).get('workstream_id'),
                     'plan_sha256':state.get('workstream_context',{}).get('plan_sha256')};rows.append(row)
            row.update(exported=True,manifest=path.relative_to(root).as_posix(),
                       report=(path.parent/'files'/manifest['report']).relative_to(root).as_posix())
        except (OSError,ValueError,TypeError,KeyError) as exc:warnings.append(f'{path.relative_to(root)}: {exc}')
    return rows,warnings


def overview(root):
    from .trace import inspect
    from .approval import approval_plan,latest_review,_review_dir
    from .design_quality import bindings,validate_binding,has_contract
    root=Path(root)
    if not inside(root,'.specify/workbench.json').is_file():
        runs,warnings=research_status(root)
        return {'inspection_only':True,'system':'未準備','docs_dir':'docs/upstream','stage':'setup_required',
                'research_stage':'standalone' if runs else 'not_planned','documents':[],'research':runs,'workstreams':[],
                'checkpoint':None,'review':None,'next_action':'対象とsystem IDを確認し、attachの差分を読んで準備する。',
                'findings':[],'warnings':warnings,'scope':'既存の記録を表示するだけです。プロジェクトは変更していません。'}
    config=load_project(root);result=inspect(root,'draft');plan=approval_plan(root)
    checkpoint=next((r for r in plan['checkpoints'] if not r['complete']),None)
    runs,warnings=research_status(root)
    groups={}
    for row in result['items']:
        if row.get('type') in {'design','decision'} and row.get('status')!='retired':groups.setdefault(row['_file'],set()).add(row['id'])
    integrated=bool(groups)
    for name,ids in groups.items():
        try:
            text=inside(root,name).read_text('utf-8')
            if not has_contract(text):integrated=False;continue
            validate_binding(root,bindings(text),ids,config['docs_dir']+'/requirements.md')
        except (ValueError,OSError,TypeError,KeyError) as exc:integrated=False;warnings.append(str(exc))
    research_plan=inside(root,'.specify/workbench/research-plan.json');tasks=[];research_stage='not_planned'
    if research_plan.is_file():
        try:
            from .research_workstreams import load_plan,digest
            frozen=load_plan(root,'.specify/workbench/research-plan.json');signature=digest(research_plan.read_bytes())
            for task in frozen['workstreams']:
                matches=[r for r in runs if r.get('workstream_id')==task['id'] and r.get('plan_sha256')==signature and r['status']=='research_complete']
                tasks.append({'id':task['id'],'title':task['title'],'status':'complete' if len(matches)==1 else ('select_run' if matches else 'pending'),
                              'runs':[r['run_id'] for r in matches],'exported':len(matches)==1 and matches[0]['exported']})
            research_stage=('selection_required' if any(t['status']=='select_run' for t in tasks) else
                            'running_or_pending' if any(t['status']=='pending' for t in tasks) else
                            'export_pending' if any(not t['exported'] for t in tasks) else 'integration_pending')
        except (ValueError,OSError,TypeError,KeyError) as exc:research_stage='plan_invalid';warnings.append(str(exc))
    elif runs:
        research_stage='export_pending' if any(r['status']=='research_complete' and not r['exported'] for r in runs) else 'integration_pending'
    if integrated:research_stage='integrated'
    try:review=latest_review(root)
    except (WorkbenchError,OSError,ValueError):review=None
    review_path=None
    if review:
        packet=_review_dir(root)/(review['review_id']+'.md')
        if packet.is_file():review_path=packet.relative_to(root).as_posix()
        else:warnings.append('固定レビューのMarkdownが見つかりません: '+str(packet.relative_to(root)))
    checks={'requirements.md':'目的・利用場面・要件と受入条件。現状、合意、提案を区別する。',
            'design.md':'要件IDとの対応、採用方式と根拠、統合時の制約・トレードオフ。',
            'verification.md':'検証ID、対象の要件・設計ID、手順と合格条件。計画と実行結果を区別する。'}
    docs=[{'path':config['docs_dir']+'/'+name,'check':check,
           'exists':inside(root,config['docs_dir']+'/'+name).is_file(),
           'items':[{'id':r['id'],'section':r.get('_section'),'line':r['_line'],'title':r.get('title','')}
                    for r in result['items'] if r['_file']==config['docs_dir']+'/'+name]} for name,check in checks.items()]
    stage='approval_pending' if checkpoint else 'upstream_approved'
    next_action=('不足項目と検査エラーを確認し、'+checkpoint['checkpoint']+'のレビューを用意する。承認待ちIDを確認する。' if checkpoint else
                 'gateで上流計画の整合性を確認する。アプリの実装・動作確認は別の作業として進める。')
    if research_stage in {'plan_invalid','selection_required','export_pending','integration_pending','running_or_pending'}:
        next_action={'plan_invalid':'研究計画と最新の要件の差分を確認し、計画を再固定する。',
                     'selection_required':'各研究テーマの採用run IDを明示して選ぶ。日時で自動選択しない。',
                     'export_pending':'採用するrunをexport-evidenceで確認・出力し、設計に関連IDと根拠を結ぶ。',
                     'integration_pending':'固定した研究報告を読み、全体の設計と検証計画に反映する。',
                     'running_or_pending':'研究テーマの依存関係と中断状態を確認して進める。'}[research_stage]
    return {'inspection_only':True,'system':config['system'],'docs_dir':config['docs_dir'],'stage':stage,
            'research_stage':research_stage,'documents':docs,'research':runs,'workstreams':tasks,
            'checkpoint':checkpoint,'review':({'id':review['review_id'],'path':review_path} if review else None),
            'next_action':next_action,'findings':result['findings'],'warnings':warnings,
            'scope':'上流文書と記録の整合性。研究完了、設計への統合、ユーザー承認、アプリの動作成功は別々に判断する。'}


def render(data,base=None):
    import os
    def link(path,label=None):
        name=os.path.relpath(path,base) if base else path
        return f'[{label or path}]({name})'
    lines=['# 上流作業の確認ページ','',f"対象: {data['system']} / 上流: {data['stage']} / 研究: {data['research_stage']}",'',
           data['next_action'],'','## 確認する文書','']
    for doc in data['documents']:
        lines+=[f"- {link(doc['path'])}：{doc['check']}"+('（未作成）' if not doc['exists'] else '')]
        for row in doc['items']:
            lines.append(f"  - `{row['id']}` — {row['title']}（節 `{row['section'] or '文書全体'}`、{row['line']}行）")
    if data['checkpoint']:
        c=data['checkpoint'];lines+=['','## 今回の確認・承認待ち','',f"確認段階: `{c['checkpoint']}`",'対象ID: '+(', '.join(c['pending']) or '不足項目を追加する'),
                                      '不足区分: '+(', '.join(c['missing_categories']) or 'なし')]
    if data['review']:
        r=data['review'];lines+=['',f"最新レビュー: `{r['id']}`"+((' / '+link(r['path'])) if r['path'] else '')]
    lines+=['','## 研究と設計への反映','']
    if not data['research']:lines+=['研究の実行記録はありません。標準的な設計で足りるか、研究が必要かを要件から判断します。']
    for row in data['research']:
        report=row.get('report') or f"docs/design-research/{row['topic']}/report.md"
        lines+=[f"- `{row['topic']} / {row['run_id']}`: {row['status']} / 証拠 {'公開済み' if row['exported'] else '未出力'} / {link(report)}"]
    if data['findings'] or data['warnings']:
        lines+=['','## 未解決の確認事項','']
        lines += [f"- [{f['severity']}] {f['item']}: {f['message']}" for f in data['findings']]
        lines += ['- '+w for w in data['warnings']]
    lines+=['','## 次の操作','',data['next_action'],'',data['scope'],'',
            'このページは生成された案内です。正本は上の文書です。直接編集せず、`speckit-workbench overview --project . --write`で更新します。','']
    return '\n'.join(lines)


def write(root,data=None):
    config=load_project(root);target=inside(root,config['docs_dir']+'/README.md')
    if target.exists() and not owned_navigation(root,target):
        raise WorkbenchError('既存のREADME.mdは管理対象外です。内容を残して移動・統合した後にoverview --writeを実行してください。')
    text=MARKER+'\n\n'+render(data or overview(root),config['docs_dir'])
    atomic_write(target,text.encode('utf-8'))


def refresh(root):
    if inside(root,'.specify/workbench.json').is_file():
        try:write(root)
        except WorkbenchError as exc:
            import sys
            print('NOTICE: 確認ページの更新を保留: '+str(exc),file=sys.stderr)


