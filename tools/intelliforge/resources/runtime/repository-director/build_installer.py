#!/usr/bin/env python3
"""Build the offline standalone installer deterministically from readable sources."""
import argparse
import base64
import io
from pathlib import Path
import zipfile

ROOT=Path(__file__).resolve().parent


def render():
    buffer=io.BytesIO()
    with zipfile.ZipFile(buffer,'w',zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(ROOT.rglob('*')):
            rel=path.relative_to(ROOT)
            if not path.is_file() or any(p in ('__pycache__','evals') for p in rel.parts) or path.suffix=='.pyc' or rel.name=='build_installer.py':continue
            if path.is_symlink():raise ValueError('Linked source: '+str(path))
            info=zipfile.ZipInfo(rel.as_posix(),(2020,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED
            archive.writestr(info,path.read_bytes())
    encoded=base64.b64encode(buffer.getvalue()).decode()
    body='''#!/usr/bin/env bash
# Generated by tools/repository-director/build_installer.py. No network bootstrap.
set -euo pipefail
exec "${PYTHON_BIN:-python3}" - "$@" <<'REPOSITORY_DIRECTOR_PY'
import base64, io, os, pathlib, subprocess, sys, tempfile, zipfile
if sys.version_info < (3,11):
    raise SystemExit('Python >=3.11 is required')
PAYLOAD = %r
with tempfile.TemporaryDirectory(prefix='repository-director-installer-') as temp:
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))) as archive:
        for member in archive.infolist():
            rel = pathlib.PurePosixPath(member.filename)
            if rel.is_absolute() or '..' in rel.parts or '\\\\' in member.filename:
                raise SystemExit('Invalid archive path')
        archive.extractall(temp)
    result=subprocess.run([sys.executable,'-B',str(pathlib.Path(temp)/'install.py'),*sys.argv[1:]],env={**os.environ,'PYTHONDONTWRITEBYTECODE':'1'})
    raise SystemExit(result.returncode)
REPOSITORY_DIRECTOR_PY
'''
    return (body % encoded).encode()


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    target=ROOT.parents[1]/'install_repository_director.sh';data=render()
    if a.check:
        if not target.is_file() or target.read_bytes()!=data:raise SystemExit('Stale Repository Director installer')
    else:target.write_bytes(data);target.chmod(0o755)



from agent_intelliforge.runtime_ports import apply_ports as _apply_ports, portable_link as _portable_link
_apply_ports(globals())
if __name__=='__main__':main()
